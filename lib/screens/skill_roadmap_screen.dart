                  ),
                ],
              ),
            ],
          ),
        ),
      ),
    ).animate().fadeIn(duration: 600.ms, delay: 200.ms).slideY(begin: 0.2);
  }

  Widget _buildWeekSection(String title, List<DailyTask> tasks, int weekNumber) {
    final weekCompleted = tasks.every((t) => t.isCompleted);

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Container(
              width: 8,
              height: 8,
              decoration: BoxDecoration(
                color: weekCompleted ? AppColors.success : AppColors.teal,
                shape: BoxShape.circle,
              ),
            ),
            const SizedBox(width: 12),
            Text(
              title,
              style: Theme.of(context).textTheme.titleLarge?.copyWith(
                fontWeight: FontWeight.w800,
              ),
            ),
            if (weekCompleted) ...[
              const SizedBox(width: 8),
              const Icon(Icons.check_circle_rounded, color: AppColors.success, size: 20),
            ],
          ],
        ),
        const SizedBox(height: 16),

        // Day Cards
        ...tasks.asMap().entries.map((entry) {
          final index = entry.key;
          return Padding(
            padding: const EdgeInsets.only(bottom: 12),
            child: _buildDayCard(entry.value).animate()
                .fadeIn(duration: 600.ms, delay: (400 + index * 50).ms)
                .slideX(begin: 0.1),
          );
        }),
      ],
    );
  }

  Widget _buildDayCard(DailyTask task) {
    Color statusColor;
    IconData statusIcon;

    if (task.isCompleted) {
      statusColor = AppColors.success;
      statusIcon = Icons.check_circle_rounded;
    } else if (task.isCurrent) {
      statusColor = AppColors.teal;
      statusIcon = Icons.play_circle_filled_rounded;
    } else if (task.isLocked) {
      statusColor = AppColors.textSecondary.withValues(alpha: 0.3);
      statusIcon = Icons.lock_rounded;
    } else {
      statusColor = AppColors.amber;
      statusIcon = Icons.circle_outlined;
    }

    return GlassContainer(
      color: task.isCurrent
          ? AppColors.teal.withValues(alpha: 0.05)
          : task.isLocked
          ? AppColors.surface.withValues(alpha: 0.02)
          : Colors.transparent,
      border: task.isCurrent
          ? Border.all(color: AppColors.teal.withValues(alpha: 0.5), width: 2)
          : null,
      child: InkWell(
        onTap: task.isLocked ? null : () {
          Navigator.push(
            context,
            MaterialPageRoute(
              builder: (_) => DailyTaskScreen(task: task, skillName: widget.skillName),
            ),
          );
        },
        borderRadius: BorderRadius.circular(16),
        child: Padding(
          padding: const EdgeInsets.all(16),
          child: Row(
            children: [
              // Day Number
              Container(
                width: 48,
                height: 48,
                decoration: BoxDecoration(
                  color: statusColor.withValues(alpha: 0.15),
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(
                    color: statusColor.withValues(alpha: 0.3),
                    width: 2,
                  ),
                ),
                child: Center(
                  child: Text(
                    '${task.day}',
                    style: TextStyle(
                      color: statusColor,
                      fontWeight: FontWeight.w900,
                      fontSize: 18,
                    ),
                  ),
                ),
              ),
              const SizedBox(width: 16),

              // Task Info
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      task.description,
                      style: Theme.of(context).textTheme.bodyLarge?.copyWith(
                        fontWeight: FontWeight.w700,
                        color: task.isLocked
                            ? AppColors.textSecondary.withValues(alpha: 0.5)
                            : AppColors.textPrimary,
                      ),
                      maxLines: 2,
                      overflow: TextOverflow.ellipsis,
                    ),
                    const SizedBox(height: 6),
                    Row(
                      children: [
                        Container(
                          padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
                          decoration: BoxDecoration(
                            color: _getDifficultyColor(task.difficulty).withValues(alpha: 0.15),
                            borderRadius: BorderRadius.circular(6),
                          ),
                          child: Text(
                            task.difficulty,
                            style: TextStyle(
                              fontSize: 10,
                              fontWeight: FontWeight.w800,
                              color: _getDifficultyColor(task.difficulty),
                            ),
                          ),
                        ),
                        const SizedBox(width: 8),
                        Icon(Icons.timer_outlined, size: 12, color: AppColors.textSecondary),
                        const SizedBox(width: 4),
                        Text(
                          '${task.estimatedMinutes}m',
                          style: TextStyle(
                            fontSize: 11,
                            fontWeight: FontWeight.w600,
                            color: AppColors.textSecondary,
                          ),
                        ),
                        const SizedBox(width: 8),
                        Icon(Icons.stars_rounded, size: 12, color: AppColors.amber),
                        const SizedBox(width: 4),
                        Text(
                          '+${task.xpReward} XP',
                          style: TextStyle(
                            fontSize: 11,
                            fontWeight: FontWeight.w700,
                            color: AppColors.amber,
                          ),
                        ),
                      ],
                    ),
                  ],
                ),
              ),

              // Status Icon
              Icon(
                statusIcon,
                color: statusColor,
                size: 28,
              ),
            ],
          ),
        ),
      ),
    );
  }

  Color _getDifficultyColor(String difficulty) {
    switch (difficulty.toLowerCase()) {
      case 'beginner':
        return AppColors.success;
      case 'intermediate':
        return AppColors.amber;
      case 'advanced':
        return AppColors.purple;
      case 'expert':
        return AppColors.error;
      default:
        return AppColors.teal;
    }
  }
}

// Model Classes
class DailyTask {
  final int day;
  final String title;
  final String description;
  final int estimatedMinutes;
  final int xpReward;
  final bool isCompleted;
  final bool isCurrent;
  final bool isLocked;
  final String difficulty;

  DailyTask({
    required this.day,
    required this.title,
    required this.description,
    required this.estimatedMinutes,
    required this.xpReward,
    required this.isCompleted,
    required this.isCurrent,
    required this.isLocked,
    required this.difficulty,
  });
}